def _kdf_checks():
    def evp():
        key, iv = evp_bytes_to_key(EV_PASSWORD, EV_SALT, 32, 16, "md5")
        _require(key == EV_KEY, "EVP_BytesToKey key mismatch")
        _require(iv == EV_IV, "EVP_BytesToKey IV mismatch")

    def pbkdf2_sha1():
        _require(
            pbkdf2(b"password", b"salt", 1, 20, "sha1").hex()
            == "0c60c80f961f0e71f3a9b524af6012062fe037a6",
            "PBKDF2 one-iteration vector mismatch",
        )
        _require(
            pbkdf2(b"password", b"salt", 4096, 20, "sha1").hex()
            == "4b007901b765489abead49d926f721d065a429c1",
            "PBKDF2 4096-iteration vector mismatch",
        )

    def aescrypt_stretch():
        from ..kdf import aescrypt_stretch as stretch

        key = stretch("hunter2".encode("utf-16-le"), AESCRYPT_IV1)
        _require(key == AESCRYPT_STRETCH_KEY, "AES Crypt stretch vector mismatch")

    def padding():
        padded = pkcs7_pad(b"A" * 70)
        _require(len(padded) == 80, "PKCS#7 padding length mismatch")
        _require(pkcs7_unpad(padded) == b"A" * 70, "PKCS#7 roundtrip failed")
        try:
            pkcs7_unpad(b"\x00" * 16)
        except Exception:
            return
        raise SelfTestFailure("invalid PKCS#7 padding was accepted")

    return {
        "EVP_BytesToKey known-answer": evp,
        "PBKDF2-HMAC-SHA1 RFC 6070": pbkdf2_sha1,
        "AES Crypt stretching known-answer": aescrypt_stretch,
        "PKCS#7 validation": padding,
    }


def _fixture_checks(tmp: Path):
    path = tmp / "pyaes.aes"
    path.write_bytes(_b64(AESCRYPT_FIXTURE))
    artifact = AesCryptArtifact(path)
    verifier = artifact.verifier(ValidationPolicy())

    def header():
        _require(artifact.header.version == 2, "AES Crypt version mismatch")
        _require(
            artifact.header.ciphertext_length == 80,
            "AES Crypt ciphertext length mismatch",
        )
        _require(artifact.header.plaintext_length == 70, "AES Crypt length mismatch")

    def verify_ok():
        _require(
            verifier.verify(b"hunter2") == Outcome.CONFIRMED,
            "correct AES Crypt password was not confirmed",
        )

    def verify_bad():
        _require(
            verifier.verify(b"wrong") == Outcome.REJECT,
            "wrong AES Crypt password was accepted",
        )

    def decrypt():
        out = io.BytesIO()
        artifact.decrypt(b"hunter2", out)
        _require(out.getvalue() == PLAINTEXT, "AES Crypt plaintext mismatch")

    def roundtrip():
        encoded = aescrypt_encrypt_bytes(PLAINTEXT, b"selftest")
        new_path = tmp / "roundtrip.aes"
        new_path.write_bytes(encoded)
        new_artifact = AesCryptArtifact(new_path)
        out = io.BytesIO()
        new_artifact.decrypt(b"selftest", out)
        _require(out.getvalue() == PLAINTEXT, "AES Crypt encryption roundtrip failed")

    def v3_roundtrip():
        encoded = aescrypt_encrypt_bytes(PLAINTEXT, b"selftest", version=3, iterations=5)
        new_path = tmp / "roundtrip-v3.aes"
        new_path.write_bytes(encoded)
        new_artifact = AesCryptArtifact(new_path)
        _require(new_artifact.header.version == 3, "AES Crypt v3 header mismatch")
        out = io.BytesIO()
        new_artifact.decrypt(b"selftest", out)
        _require(
            out.getvalue() == PLAINTEXT,
            "AES Crypt v3 encryption roundtrip failed",
        )

    return {
        "AES Crypt v2 header parse": header,
        "AES Crypt password verify": verify_ok,
        "AES Crypt rejects wrong password": verify_bad,
        "AES Crypt decrypt fixture": decrypt,
        "AES Crypt encrypt roundtrip": roundtrip,
        "AES Crypt v3 encrypt roundtrip": v3_roundtrip,
    }


def _openssl_checks(tmp: Path):
    checks: dict[str, Callable[[], None]] = {}
    for name, (encoded, options, prefix) in OPENSSL_FIXTURES.items():
        path = tmp / f"openssl-{name}.bin"
        path.write_bytes(_b64(encoded))

        def decrypt_check(path=path, options=options, prefix=prefix) -> None:
            artifact = OpenSSLArtifact(path, options)
            verifier = artifact.verifier(ValidationPolicy("auto", prefix))
            outcome = verifier.verify(b"hunter2")
            expected = Outcome.CONFIRMED if prefix else Outcome.PROBABLE
            _require(
                outcome >= expected,
                f"OpenSSL candidate was not accepted (got {outcome.name})",
            )
            _require(
                verifier.verify(b"wrong") == Outcome.REJECT,
                "OpenSSL verifier accepted a wrong password",
            )
            out = io.BytesIO()
            artifact.decrypt(b"hunter2", out)
            _require(out.getvalue() == PLAINTEXT, "OpenSSL plaintext mismatch")

        checks[f"OpenSSL {name} decrypt"] = decrypt_check

    def roundtrip():
        from ..formats.openssl_enc import encrypt_bytes

        encoded = encrypt_bytes(
            PLAINTEXT,
            b"selftest",
            cipher_name="aes-256-cbc",
            digest="sha256",
        )
        path = tmp / "openssl-roundtrip.enc"
        path.write_bytes(encoded)
        artifact = OpenSSLArtifact(path, FormatOptions(cipher="aes-256-cbc", digest="sha256"))
        _require(
            artifact.verifier(ValidationPolicy()).verify(b"selftest") >= Outcome.PROBABLE,
            "OpenSSL roundtrip password was rejected",
        )
        out = io.BytesIO()
        artifact.decrypt(b"selftest", out)
        _require(out.getvalue() == PLAINTEXT, "OpenSSL roundtrip plaintext mismatch")

    checks["OpenSSL enc encrypt roundtrip"] = roundtrip
    return checks



def _custom_checks(tmp: Path):
    def cbc_prefix():
        salt = bytes(range(16))
        iv = bytes(range(16, 32))
        key = pbkdf2(b"hunter2", salt, 1000, 32, "sha256")
        ciphertext = aes_cbc_encrypt(key, iv, pkcs7_pad(PLAINTEXT))
        (tmp / "custom-cbc.b64").write_text(base64.b64encode(salt + iv + ciphertext).decode())
        spec = {
            "cipher": "aes-256-cbc",
            "input_encoding": "base64",
            "ciphertext_offset": 32,
            "kdf": {
                "type": "pbkdf2",
                "digest": "sha256",
                "iterations": 1000,
                "salt_offset": 0,
                "salt_length": 16,
            },
            "iv": {"source": "embedded", "offset": 16, "length": 16},
            "padding": "pkcs7",
            "oracle": {"type": "known_prefix", "hex": PLAINTEXT[:16].hex()},
        }
        (tmp / "custom-cbc.json").write_text(json.dumps(spec))
        artifact = CustomArtifact(tmp / "custom-cbc.b64", tmp / "custom-cbc.json")
        verifier = artifact.verifier(ValidationPolicy())
        _require(
            verifier.verify(b"hunter2") == Outcome.CONFIRMED,
            "custom CBC prefix did not confirm",
        )
        _require(
            verifier.verify(b"wrong") == Outcome.REJECT,
            "custom CBC prefix accepted a wrong password",
        )
        out = io.BytesIO()
        artifact.decrypt(b"hunter2", out)
        _require(out.getvalue() == PLAINTEXT, "custom CBC decrypt mismatch")

    def gcm_tag():
        salt = b"custom-salt"
        key = pbkdf2(b"hunter2", salt, 1000, 32, "sha256")
        nonce = bytes(range(12))
        aad = b"custom-aad"
        ciphertext, tag = aes_gcm_encrypt(key, nonce, PLAINTEXT, aad=aad)
        (tmp / "custom-gcm.bin").write_bytes(nonce + ciphertext + tag)
        spec = {
            "cipher": "aes-256-gcm",
            "input_encoding": "raw",
            "ciphertext_offset": 12,
            "ciphertext_length": len(ciphertext),
            "kdf": {
                "type": "pbkdf2",
                "digest": "sha256",
                "iterations": 1000,
                "salt_hex": salt.hex(),
            },
            "iv": {"source": "embedded", "offset": 0, "length": 12},
            "padding": "none",
            "oracle": {
                "type": "gcm_tag",
                "tag_offset": 12 + len(ciphertext),
                "tag_length": len(tag),
                "aad_hex": aad.hex(),
            },
        }
        (tmp / "custom-gcm.json").write_text(json.dumps(spec))
        artifact = CustomArtifact(tmp / "custom-gcm.bin", tmp / "custom-gcm.json")
        verifier = artifact.verifier(ValidationPolicy())
        _require(
            verifier.verify(b"hunter2") == Outcome.CONFIRMED,
            "custom GCM tag did not confirm",
        )
        _require(
            verifier.verify(b"wrong") == Outcome.REJECT,
            "custom GCM tag accepted a wrong password",
        )

    return {
        "Custom spec CBC known prefix": cbc_prefix,
        "Custom spec GCM tag": gcm_tag,
    }


def _logic_checks(tmp: Path):
    def rules():
        _require(parse_rule("c$1").apply(b"hunter") == b"Hunter1", "case rule failed")
        _require(parse_rule("sa@se3").apply(b"secret") == b"s3cr3t", "leet rule failed")
        _require(parse_rule("<3").apply(b"abc") is None, "rejection rule failed")

    def masks():
        plan = parse_mask("?d?d")
        _require(plan.keyspace == 100, "mask keyspace mismatch")
        _require(plan.index_to_bytes(42) == b"42", "mask index mapping failed")
        enumerated = list(plan.iter_bytes())
        _require(len(enumerated) == 100, "mask enumeration length mismatch")
        charset = build_charset_plan("ab", min_length=1, max_length=3)
        _require(charset.keyspace == 14, "charset keyspace mismatch")

    def cribdrag_logic():
        from ..crypto import xor_bytes

        left = b"attack at dawn"
        right = b"retreat now!!"
        xor = xor_bytes(left, right)
        _require(
            xor_bytes(xor[7:10], b"at ") == right[7:10],
            "crib XOR reasoning failed",
        )

    return {
        "Rule engine semantics": rules,
        "Mask enumeration": masks,
        "CTR crib XOR": cribdrag_logic,
    }


def _optional_checks(tmp: Path):
    checks: dict[str, Callable[[], None]] = {}

    try:
        import pyAesCrypt
    except Exception:
        pyAesCrypt = None

    if pyAesCrypt is not None:

        def pyAesCrypt_cross():
            plain_path = tmp / "pyaes-plain.bin"
            enc_path = tmp / "pyaes-generated.aes"
            dec_path = tmp / "pyaes-decrypted.bin"
            plain_path.write_bytes(PLAINTEXT)
            pyAesCrypt.encryptFile(str(plain_path), str(enc_path), "hunter2")
            artifact = AesCryptArtifact(enc_path)
            out = io.BytesIO()
            artifact.decrypt(b"hunter2", out)
            _require(out.getvalue() == PLAINTEXT, "pyAesCrypt file did not decrypt")

            our_enc = tmp / "our-generated.aes"
            our_enc.write_bytes(aescrypt_encrypt_bytes(PLAINTEXT, b"hunter2"))
            pyAesCrypt.decryptFile(str(our_enc), str(dec_path), "hunter2")
            _require(
                dec_path.read_bytes() == PLAINTEXT,
                "pyAesCrypt could not decrypt our file",
            )

        checks["pyAesCrypt interoperability"] = pyAesCrypt_cross
    else:

        def pyAesCrypt_skip():
            raise _Skip("pyAesCrypt is not installed")

        checks["pyAesCrypt interoperability"] = pyAesCrypt_skip

    openssl = shutil.which("openssl")
    if openssl:

        def openssl_cross():
            from ..formats.openssl_enc import encrypt_bytes

            enc_path = tmp / "openssl-generated.enc"
            enc_path.write_bytes(
                encrypt_bytes(
                    PLAINTEXT,
                    b"hunter2",
                    cipher_name="aes-256-cbc",
                    digest="sha256",
                )
            )
            result = subprocess.run(
                [
                    openssl,
                    "enc",
                    "-d",
                    "-aes-256-cbc",
                    "-md",
                    "sha256",
                    "-in",
                    str(enc_path),
                    "-pass",
                    "pass:hunter2",
                ],
                capture_output=True,
                timeout=30,
            )
            _require(result.returncode == 0, f"openssl failed: {result.stderr!r}")
            _require(result.stdout == PLAINTEXT, "openssl decrypted different bytes")

        checks["OpenSSL binary interoperability"] = openssl_cross
    else:

        def openssl_skip():
            raise _Skip("openssl binary is not installed")

        checks["OpenSSL binary interoperability"] = openssl_skip

    sevenzip = shutil.which("7z") or shutil.which("7za") or shutil.which("7zr")
    if sevenzip:

        def sevenzip_cross():
            zip_path = tmp / "sevenzip-generated.zip"
            zip_path.write_bytes(build_zip_aes("selftest.txt", PLAINTEXT, b"hunter2"))
            result = subprocess.run(
                [sevenzip, "t", "-phunter2", str(zip_path)],
                capture_output=True,
                timeout=30,
            )
            _require(
                result.returncode == 0,
                f"7-Zip rejected our archive: {result.stdout!r} {result.stderr!r}",
            )

        checks["7-Zip interoperability"] = sevenzip_cross
    else:

        def sevenzip_skip():
            raise _Skip("7z is not installed")

        checks["7-Zip interoperability"] = sevenzip_skip

    return checks


def _engine_checks(tmp: Path):
    path = tmp / "pyaes.aes"
    if not path.exists():
        path.write_bytes(_b64(AESCRYPT_FIXTURE))
    wordlist = tmp / "selftest-words.txt"
    wordlist.write_bytes(b"wrong\nhunter2\n")
    artifact = AesCryptArtifact(path)

    def run_jobs(jobs: int):
        plan = build_plan(PlanOptions(wordlist=str(wordlist), count_lines=True))
        verifier = artifact.verifier(ValidationPolicy())
        result = run_attack(
            verifier,
            plan,
            AttackConfig(jobs=jobs, show_status=False),
        )
        _require(result.found == b"hunter2", f"engine with {jobs} job(s) missed the password")
        _require(result.attempts == 2, f"engine attempt count mismatch: {result.attempts}")

    def serial():
        run_jobs(1)

    def parallel():
        run_jobs(2)

    checks = {"Attack engine (serial)": serial}
    if os.name == "posix" or sys.platform == "win32":
        checks["Attack engine (multiprocess)"] = parallel
    return checks


def run_selftest(*, include_process: bool = True, json_output: bool = False) -> int:
    checks: dict[str, Callable[[], None]] = {}
    checks.update(_nist_checks())
    checks.update(_kdf_checks())
    checks.update(_logic_checks(Path(".")))

    with tempfile.TemporaryDirectory(prefix="aesbreaker-selftest-") as raw_tmp:
        tmp = Path(raw_tmp)
        checks.update(_fixture_checks(tmp))
        checks.update(_openssl_checks(tmp))
        checks.update(_zip_checks(tmp))
        checks.update(_custom_checks(tmp))
        checks.update(_optional_checks(tmp))
        if include_process:
            checks.update(_engine_checks(tmp))
        else:

            def skip_process():
                raise _Skip("multiprocess engine checks disabled")

            checks["Attack engine (multiprocess)"] = skip_process

        results: list[dict[str, object]] = []
        for name, function in checks.items():
            try:
                function()
            except _Skip as exc:
                results.append({"name": name, "status": "SKIP", "detail": str(exc)})
            except Exception as exc:  # noqa: BLE001 - report every failure
                detail = f"{type(exc).__name__}: {exc}"
                results.append(
                    {
                        "name": name,
                        "status": "FAIL",
                        "detail": detail,
                        "traceback": traceback.format_exc(),
                    }
                )
            else:
                results.append({"name": name, "status": "PASS", "detail": None})

    passed = sum(1 for item in results if item["status"] == "PASS")
    failed = sum(1 for item in results if item["status"] == "FAIL")
    skipped_count = sum(1 for item in results if item["status"] == "SKIP")
    payload = {
        "tool": "aesbreaker",
        "version": __version__,
        "command": "selftest",
        "checks": [
            {key: value for key, value in item.items() if key != "traceback"} for item in results
        ],
        "passed": passed,
        "failed": failed,
        "skipped": skipped_count,
    }
    if json_output:
        write_json(None, payload)
        return 0 if failed == 0 else 1

    print(f"AES-Breaker selftest {__version__}")
    for item in results:
        if item["status"] == "FAIL":
            print(f"[FAIL] {item['name']}: {item['detail']}")
            print(str(item.get("traceback", "")).rstrip())
        elif item["status"] == "SKIP":
            print(f"[SKIP] {item['name']}: {item['detail']}")
        else:
            print(f"[PASS] {item['name']}")
    print(f"Summary: {passed} passed, {failed} failed, {skipped_count} skipped")
    return 0 if failed == 0 else 1


def configure(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--no-process",
        action="store_true",
        help="skip the multiprocess engine check",
    )
    parser.add_argument("--json", action="store_true", help="write the results as JSON")


def run(args: argparse.Namespace) -> int:
    return run_selftest(
        include_process=not args.no_process,
        json_output=args.json,
    )
